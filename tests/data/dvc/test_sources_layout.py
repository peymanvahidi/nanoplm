def _gen(cfg, kind="pretrain", fn="data.yaml"):
    return generate_dvc_yaml(cfg, kind, fn).replace(str(_NANOPLM_PKG_DIR), "<PKG>")


@pytest.mark.parametrize("name, fn, kind", [
    ("url_gz", "data.yaml", "pretrain"), ("local_gz", "data.yaml", "pretrain"),
    ("local_plain", "data.yaml", "pretrain"),
    ("distill", "distillation_data.yaml", "distillation")])
def test_old_configs_give_masters_dvc_yaml_byte_for_byte(name, fn, kind):
    """An existing project keeps a valid dvc.lock: nothing reruns after the upgrade."""
    cfg = yaml.safe_load((GOLDEN / f"{name}.{fn}").read_text())
    assert _gen(cfg, kind, fn) == (GOLDEN / f"{name}.dvc.yaml").read_text()


def test_the_template_matches_masters_template_stage_for_stage():
    """The sources layout moves the paths under output_dir and drops the data_dirs params,
    and writes a field at its default as a value instead of a param; otherwise every
    stage is master's: same names, commands, deps, params and outs."""
    old_cfg = yaml.safe_load((GOLDEN / "url_gz.data.yaml").read_text())
    old = yaml.safe_load((GOLDEN / "url_gz.dvc.yaml").read_text())["stages"]
    new = yaml.safe_load(_gen(yaml.safe_load(load_template("data_pretrain"))))["stages"]
    src = parse_data_config(yaml.safe_load(load_template("data_pretrain"))).source
    to_new = {f"${{data_dirs.{k}}}": v for k, v in src.paths.items() if v}
    to_new["${data_dirs.url}"] = src.fasta
    to_new["${data_params.seqs_num}"] = "${data_params.max_seqs}"
    to_new.update({f"${{data_params.{f}}}": literal(src.params[f]) for f in src.defaulted})
    assert src.defaulted == {"shuffle", "shuffle_seed", "samples_per_shard", "max_workers",
                             "register_tokens", "drop_invalid_sequences"}
    assert old_cfg["data_dirs"]["url"] == src.fasta

    def moved(x):
        if isinstance(x, str):
            return re.sub(r"\$\{(data_dirs|data_params)\.\w+\}",
                          lambda m: to_new.get(m.group(0), m.group(0)), x)
        if isinstance(x, list):
            return [moved(v) for v in x]
        if isinstance(x, dict):
            return {k: moved(v) for k, v in x.items()}
        return x

    def params(stage):
        keys = [k for p in stage.get("params", []) for k in p["data.yaml"]]
        return [k.replace("seqs_num", "max_seqs") for k in keys
                if not k.startswith("data_dirs.") and k[len("data_params."):] not in src.defaulted]

    assert list(new) == list(old)
    for name in old:
        o, n = old[name], new[name]
        o, n = (o["do"], n["do"]) if "foreach" in o else (o, n)
        assert moved(o["cmd"]) == n["cmd"], name
        deps = moved(o["deps"])
        if name == "get_file":     # a download depends only on its URL, in the command
            deps = [d for d in deps if not d.endswith("/downloader.py")]
        assert deps == n.get("deps", []), name
        assert moved(o["outs"]) == n["outs"], name
        assert params(o) == params(n), name
    assert moved(old["pre-tokenize"]["foreach"]) == new["pre-tokenize"]["foreach"]


