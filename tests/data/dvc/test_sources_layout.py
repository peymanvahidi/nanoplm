"""dvc.yaml and `nanoplm data from-yaml` for the sources layout and the old data_dirs one.

golden/ holds master's dvc.yaml for four old configs, generated by master's
_dvc_yaml_gen with the package path replaced by <PKG>.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest
import yaml
from click.testing import CliRunner

from nanoplm.cli._dvc_yaml_gen import _NANOPLM_PKG_DIR, generate_dvc_yaml
from nanoplm.cli.data import data
from nanoplm.cli.templates import load_template
from nanoplm.data.preparation.data_config import parse_data_config

GOLDEN = Path(__file__).parent / "golden"


def _gen(cfg, kind="pretrain", fn="data.yaml"):
    return generate_dvc_yaml(cfg, kind, fn).replace(str(_NANOPLM_PKG_DIR), "<PKG>")


@pytest.mark.parametrize("name, fn, kind", [
    ("url_gz", "data.yaml", "pretrain"), ("local_gz", "data.yaml", "pretrain"),
    ("local_plain", "data.yaml", "pretrain"),
    ("distill", "distillation_data.yaml", "distillation")])
def test_old_configs_give_masters_dvc_yaml_byte_for_byte(name, fn, kind):
    """An existing project keeps a valid dvc.lock: nothing reruns after the upgrade."""
    cfg = yaml.safe_load((GOLDEN / f"{name}.{fn}").read_text())
    assert _gen(cfg, kind, fn) == (GOLDEN / f"{name}.dvc.yaml").read_text()


def test_the_template_matches_masters_template_stage_for_stage():
    """The sources layout moves the paths under output_dir and drops the data_dirs params;
    otherwise every stage is master's: same names, commands, deps, params and outs."""
    old_cfg = yaml.safe_load((GOLDEN / "url_gz.data.yaml").read_text())
    old = yaml.safe_load((GOLDEN / "url_gz.dvc.yaml").read_text())["stages"]
    new = yaml.safe_load(_gen(yaml.safe_load(load_template("data_pretrain"))))["stages"]
    src = parse_data_config(yaml.safe_load(load_template("data_pretrain"))).source
    to_new = {f"${{data_dirs.{k}}}": v for k, v in src.paths.items() if v}
    to_new["${data_dirs.url}"] = src.fasta
    to_new["${data_params.seqs_num}"] = "${data_params.max_seqs}"
    assert old_cfg["data_dirs"]["url"] == src.fasta

    def moved(x):
        if isinstance(x, str):
            return re.sub(r"\$\{(data_dirs|data_params)\.\w+\}",
                          lambda m: to_new.get(m.group(0), m.group(0)), x)
        if isinstance(x, list):
            return [moved(v) for v in x]
        if isinstance(x, dict):
            return {k: moved(v) for k, v in x.items()}
        return x

    def params(stage):
        keys = [k for p in stage.get("params", []) for k in p["data.yaml"]]
        return [k.replace("seqs_num", "max_seqs") for k in keys if not k.startswith("data_dirs.")]

    assert list(new) == list(old)
    for name in old:
        o, n = old[name], new[name]
        o, n = (o["do"], n["do"]) if "foreach" in o else (o, n)
        assert moved(o["cmd"]) == n["cmd"], name
        assert moved(o["deps"]) == n["deps"], name
        assert moved(o["outs"]) == n["outs"], name
        assert params(o) == params(n), name
    assert moved(old["pre-tokenize"]["foreach"]) == new["pre-tokenize"]["foreach"]


# ------------------------------------------------------------------ from-yaml


def _write(tmp_path, cfg):
    p = tmp_path / "data.yaml"
    p.write_text(cfg if isinstance(cfg, str) else yaml.safe_dump(cfg, sort_keys=False))
    return p


def _no_dvc(monkeypatch):
    monkeypatch.setattr("subprocess.run", lambda *a, **k: pytest.fail("DVC must not run"))


def _run(path, *args):
    return CliRunner().invoke(data, ["from-yaml", str(path), *args])


def _dry(tmp_path, monkeypatch, cfg):
    """from-yaml --dry-run with DVC stubbed; returns the output."""
    (tmp_path / ".dvc").mkdir(exist_ok=True)
    calls = []
    monkeypatch.setattr("subprocess.run", lambda *a, **k: calls.append(a) or
                        type("R", (), {"returncode": 0, "stdout": "{}"})())
    r = _run(_write(tmp_path, cfg), "--dry-run")
    assert r.exit_code == 0, r.output
    return r.output, calls


def test_summary_for_a_plain_source(tmp_path, monkeypatch):
    out, _ = _dry(tmp_path, monkeypatch, load_template("data_pretrain"))
    table = out[:out.index("Regenerated")]
    assert table == (
        f"data.yaml: 1 source -> {tmp_path}/output/data/pretrain_data\n"
        "source     fasta                         seqs    len     val  clustering\n"
        "swissprot  uniprot_sprot.fasta.gz (url)  20,000  20-512  0.1  off\n")
    assert "Rebuild: all (first run)" in out
    assert out.index("Rebuild:") < out.index("Running dvc repro")


def test_summary_for_a_uniref_cluster_source_marks_overrides(tmp_path, monkeypatch):
    cfg = yaml.safe_load(load_template("data_pretrain"))
    cfg["sources"] = {"uniref50": {"fasta": "uniref50", "max_seqs": -1, "val_ratio": 0.0044,
                                   "cluster_subsampling": {"members": "uniref90"}}}
    out, _ = _dry(tmp_path, monkeypatch, cfg)
    table = out[out.index("data.yaml: 1 source"):out.index("Regenerated")]
    assert table == (
        f"data.yaml: 1 source -> {tmp_path}/output/data/pretrain_data\n"
        "source    fasta                    seqs  len     val      clustering\n"
        "uniref50  uniref50.fasta.gz (url)  all*  20-512  0.0044*  "
        "UniProt uniref50.xml.gz (members: UniRef90)\n"
        "* = set on this source\n")


def test_summary_shows_a_reused_download_and_a_local_file(tmp_path, monkeypatch):
    got = tmp_path / "output/data/pretrain_data/downloads/uniprot_sprot.fasta.gz"
    got.parent.mkdir(parents=True)
    got.write_bytes(b"x" * 2_500_000)
    out, _ = _dry(tmp_path, monkeypatch, load_template("data_pretrain"))
    assert "uniprot_sprot.fasta.gz (reuse, 2.5 MB)" in out
    (tmp_path / "mine.fasta").write_text(">a\nMKV\n")
    cfg = yaml.safe_load(load_template("data_pretrain"))
    cfg["sources"] = {"mine": {"fasta": "mine.fasta"}}
    out, _ = _dry(tmp_path, monkeypatch, cfg)
    assert "mine.fasta (local, 7 B)" in out


def test_the_rebuild_line_asks_dvc_status_after_the_first_run(tmp_path, monkeypatch):
    (tmp_path / "dvc.lock").write_text("schema: '2.0'\n")
    (tmp_path / ".dvc").mkdir()
    status = '{"filter": [], "split": [], "pre-tokenize@train": []}'
    monkeypatch.setattr("subprocess.run", lambda *a, **k: type(
        "R", (), {"returncode": 0, "stdout": status if "status" in a[0] else ""})())
    r = _run(_write(tmp_path, load_template("data_pretrain")), "--dry-run")
    assert r.exit_code == 0, r.output
    # pre-tokenize@val and write_manifest read what split writes, so they rerun too
    assert ("Rebuild: filter, split, pre-tokenize@train, pre-tokenize@val, write_manifest. "
            "Up to date: get_file, extract, check, shuffle.") in r.output


def _rebuild_line(tmp_path, monkeypatch, cfg, status):
    (tmp_path / "dvc.lock").write_text("schema: '2.0'\n")
    (tmp_path / ".dvc").mkdir(exist_ok=True)
    monkeypatch.setattr("subprocess.run", lambda *a, **k: type(
        "R", (), {"returncode": 0, "stdout": status if "status" in a[0] else ""})())
    r = _run(_write(tmp_path, cfg), "--dry-run")
    assert r.exit_code == 0, r.output
    return next(line for line in r.output.splitlines() if line.startswith(("Rebuild", "Up to")))


def test_the_rebuild_line_follows_cluster_outputs_downstream(tmp_path, monkeypatch):
    cfg = yaml.safe_load(load_template("data_pretrain"))
    cfg["sources"] = {"uniref50": {"fasta": "uniref50",
                                   "cluster_subsampling": {"members": "uniref90"}}}
    line = _rebuild_line(tmp_path, monkeypatch, cfg, '{"cluster_members": []}')
    assert line == ("Rebuild: cluster_members, cluster_index, write_manifest. Up to date: "
                    "get_members_fasta, extract_members, check, filter, cluster_pool, "
                    "get_cluster_xml.")


def test_the_rebuild_line_resolves_old_layout_paths(tmp_path, monkeypatch):
    """data_dirs stages name their files as ${data_dirs.X}; the graph reads them from
    data.yaml."""
    line = _rebuild_line(tmp_path, monkeypatch, (GOLDEN / "url_gz.data.yaml").read_text(),
                         '{"shuffle": []}')
    assert line == ("Rebuild: shuffle, filter, split, pre-tokenize@train, pre-tokenize@val, "
                    "write_manifest. Up to date: get_file, extract, check.")


def test_old_layout_warns_with_the_block_to_paste(tmp_path, monkeypatch):
    out, _ = _dry(tmp_path, monkeypatch, (GOLDEN / "url_gz.data.yaml").read_text())
    assert "Warning: data_dirs is the old data.yaml layout" in out
    assert "sources:\n  main:\n    fasta: swissprot" in out
    assert "\nmain    sequences.fasta.gz (url)  20,000  20-512  0.1  off\n" in out
    # the dvc.yaml it writes is master's
    assert (tmp_path / "dvc.yaml").read_text().replace(str(_NANOPLM_PKG_DIR), "<PKG>") == \
        (GOLDEN / "url_gz.dvc.yaml").read_text()


def test_dvc_init_links_the_cache_for_the_sources_layout_only(tmp_path, monkeypatch):
    calls = []
    monkeypatch.setattr("subprocess.run", lambda *a, **k: calls.append(a[0]) or
                        type("R", (), {"returncode": 0, "stdout": ""})())
    new, old = tmp_path / "new", tmp_path / "old"
    new.mkdir(), old.mkdir()
    assert _run(_write(new, load_template("data_pretrain"))).exit_code == 0
    assert any(c[-3:] == ["config", "cache.type", "hardlink,symlink"] for c in calls)
    calls.clear()
    assert _run(_write(old, (GOLDEN / "local_gz.data.yaml").read_text())).exit_code == 0
    assert any("init" in c for c in calls)
    assert not any("cache.type" in c for c in calls)


@pytest.mark.parametrize("text, message", [
    ("output_dir: out\nsources:\n  a: {fasta: swissprot}\n  a: {fasta: trembl}\n",
     "data.yaml:4: duplicate key 'a' (first on line 3)"),
    ("output_dir: out\nsources:\n  a: {fasta: swissprot}\n  b: {fasta: trembl}\n"
     "data_params: {}\n",
     "mixing several sources is not supported yet (one source only)"),
    ("output_dir: out\nsources:\n  a: {fasta: swissprot, max_seq_lenn: 5}\n",
     "data.yaml: sources.a: unknown key max_seq_lenn"),
    ("output_dir: out\nsources:\n  a: {fasta: missing.fasta}\n"
     "data_params: {max_seqs: 1, min_seq_len: 1, max_seq_len: 9, val_ratio: 0.1, "
     "drop_invalid_sequences: false, shuffle: true, shuffle_seed: 1, samples_per_shard: 9, "
     "max_workers: 1, register_tokens: 0}\n",
     "data.yaml: sources.a.fasta: missing.fasta not found"),
    ("output_dir: out\nsources:\n  a:\n    fasta: uniref50\n    cluster_subsampling:\n",
     "sources.a.cluster_subsampling is empty. It needs members (null = this fasta)"),
    ("output_dir: out\nsources:\n  a:\n    fasta: uniref50\n    cluster_subsampling:\n"
     "      enabled: true\n      members: uniref90\n",
     "remove enabled; the block being present turns it on"),
])
def test_from_yaml_errors_before_dvc(tmp_path, monkeypatch, text, message):
    _no_dvc(monkeypatch)
    r = _run(_write(tmp_path, text))
    assert r.exit_code != 0 and message in " ".join(r.output.split()), r.output
    assert not (tmp_path / "dvc.yaml").exists()


def test_a_bad_override_names_the_source(tmp_path, monkeypatch):
    _no_dvc(monkeypatch)
    cfg = yaml.safe_load(load_template("data_pretrain"))
    cfg["sources"]["swissprot"]["val_ratio"] = 2
    r = _run(_write(tmp_path, cfg))
    assert r.exit_code != 0 and "sources.swissprot.val_ratio has an invalid value: 2" in r.output


def _built(folder, **extra):
    folder.mkdir(parents=True)
    (folder / ".data_manifest").write_text(yaml.safe_dump({
        "pipeline_mode": "pretrain", "seqs_num": 42, "min_seq_len": 20, "max_seq_len": 512,
        "val_ratio": 0.1, "train_dir": "train", "val_dir": "val", "train_sequences": 38,
        "val_sequences": 4, "sharded": True, "samples_per_shard": 2000, **extra}))


def test_a_prepared_source_is_checked_and_nothing_is_built(tmp_path, monkeypatch):
    _no_dvc(monkeypatch)
    _built(tmp_path / "other/out")
    cfg = {"output_dir": "out", "sources": {"mine": {"prepared": "other/out"}}}
    r = _run(_write(tmp_path, cfg))
    assert r.exit_code == 0, r.output
    folder = (tmp_path / "other/out").resolve()
    assert r.output == (f"sources.mine: prepared {folder}\n"
                        "  38 train / 4 val sequences, max_seq_len 512\n"
                        f"Nothing to build. Set pretrain.yaml's dataset_dir to {folder}.\n")
    assert not (tmp_path / "dvc.yaml").exists() and not (tmp_path / ".dvc").exists()


@pytest.mark.parametrize("setup, message", [
    (lambda p: None, "is not a folder"),
    (lambda p: p.mkdir(parents=True), "is not a built dataset"),
])
def test_a_prepared_source_must_be_a_built_folder(tmp_path, monkeypatch, setup, message):
    _no_dvc(monkeypatch)
    setup(tmp_path / "other")
    r = _run(_write(tmp_path, {"output_dir": "out", "sources": {"m": {"prepared": "other"}}}))
    assert r.exit_code != 0 and message in r.output


def test_fix_flips_an_override_too(tmp_path, monkeypatch):
    cfg = load_template("data_pretrain").replace(
        "    weight: 1.0\n", "    weight: 1.0\n    drop_invalid_sequences: false\n")
    _dry(tmp_path, monkeypatch, cfg)
    r = _run(tmp_path / "data.yaml", "--fix", "--dry-run")
    assert r.exit_code == 0, r.output
    assert (tmp_path / "data.yaml").read_text().count("drop_invalid_sequences: true") == 2
