def _write(tmp_path, cfg):
    p = tmp_path / "data.yaml"
    p.write_text(cfg if isinstance(cfg, str) else yaml.safe_dump(cfg, sort_keys=False))
    return p


def _no_dvc(monkeypatch):
    monkeypatch.setattr("subprocess.run", lambda *a, **k: pytest.fail("DVC must not run"))


def _run(path, *args):
    return CliRunner().invoke(data, ["from-yaml", str(path), *args])


def _dry(tmp_path, monkeypatch, cfg):
    """from-yaml --dry-run with DVC stubbed; returns the output."""
    (tmp_path / ".dvc").mkdir(exist_ok=True)
    calls = []
    monkeypatch.setattr("subprocess.run", lambda *a, **k: calls.append(a) or
                        type("R", (), {"returncode": 0, "stdout": "{}"})())
    r = _run(_write(tmp_path, cfg), "--dry-run")
    assert r.exit_code == 0, r.output
    return r.output, calls


